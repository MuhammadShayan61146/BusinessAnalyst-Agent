
(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory();
  } else {
    root.BALogic = factory();
  }
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";

  /**
   * Maps a canonical_status value to a badge the UI can render.
   * NEVER returns a "success"/"passed" label for anything other than
   * the literal string "passed" — this is the one rule the requirement
   * "do not show a successful validation badge if the canonical
   * validator did not report success" depends on, and it is centralized
   * here rather than scattered across rendering code.
   */
  function formatValidationBadge(canonicalStatus) {
    switch (canonicalStatus) {
      case "passed":
        return { label: "Validation passed", cssClass: "badge-success" };
      case "requires_human_review":
        return { label: "Requires human review", cssClass: "badge-warning" };
      case "failed":
        return { label: "Validation failed", cssClass: "badge-error" };
      case "mapping_error":
        return { label: "Could not validate (mapping error)", cssClass: "badge-error" };
      case null:
      case undefined:
        return { label: "Not yet validated", cssClass: "badge-neutral" };
      default:
        // Unknown value: still never claim success for something we
        // don't recognize.
        return { label: "Unknown validation status: " + String(canonicalStatus), cssClass: "badge-neutral" };
    }
  }


  function classifyRequirementEvidence(functionalRequirement) {
    var refs = functionalRequirement && functionalRequirement.source_refs;
    if (Array.isArray(refs) && refs.length > 0) {
      return "source-supported";
    }
    return "assumption-or-client-stated";
  }

  function isSessionActive(status) {
    return status === "waiting_for_input";
  }

  function isSessionComplete(status) {
    return status === "completed";
  }

  /**
   * Builds a short, human-readable summary line for a list of
   * artifacts, without fabricating content when the list is empty.
   */
  function summarizeArtifactCount(artifacts) {
    if (!artifacts || artifacts.length === 0) {
      return "No artifacts available yet.";
    }
    var n = artifacts.length;
    return n + " artifact" + (n === 1 ? "" : "s") + " available.";
  }

  function formatBytes(bytes) {
    if (typeof bytes !== "number" || bytes < 0) return "";
    if (bytes < 1024) return bytes + " B";
    if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + " KB";
    return (bytes / (1024 * 1024)).toFixed(1) + " MB";
  }


  /**
   * Builds the requirement -> user story -> acceptance criteria view.
   * Acceptance criteria are grouped by their story_id (NOT by their own id:
   * the agent can reuse ids such as "AC-1" under different stories).
   * Also reports functional requirements that no user story covers.
   */
  function buildTraceability(requirements, stories, criteria) {
    requirements = Array.isArray(requirements) ? requirements : [];
    stories = Array.isArray(stories) ? stories : [];
    criteria = Array.isArray(criteria) ? criteria : [];
    var reqById = {};
    requirements.forEach(function (r) { if (r && r.id) reqById[r.id] = r; });
    var covered = {};
    var cards = stories.map(function (st) {
      var linked = (Array.isArray(st.fr_ids) ? st.fr_ids : []).map(function (id) {
        covered[id] = true;
        var r = reqById[id];
        return { id: id, text: r ? (r.text || "") : "(requirement not found)", found: !!r };
      });
      var crit = criteria.filter(function (c) { return c && c.story_id === st.id; });
      return {
        id: st.id, as_a: st.as_a || "", i_want: st.i_want || "", so_that: st.so_that || "",
        priority: st.priority || "", requirements: linked, criteria: crit,
        missingCriteria: crit.length === 0,
      };
    });
    var uncovered = requirements.filter(function (r) { return r && r.id && !covered[r.id]; })
      .map(function (r) { return { id: r.id, text: r.text || "" }; });
    return { stories: cards, uncoveredRequirements: uncovered };
  }

  /**
   * Turns SVG text into a data: URL for use in <img src>. An SVG shown through
   * <img> cannot run scripts, which is why logos (generated by a language
   * model) are only ever displayed this way, never inserted into the page.
   * Returns "" for anything that does not look like an SVG.
   */
  function svgToDataUri(svg) {
    if (typeof svg !== "string") return "";
    var t = svg.trim();
    if (t.indexOf("<svg") !== 0) return "";
    return "data:image/svg+xml;charset=utf-8," + encodeURIComponent(t);
  }

  function authHeaders(token) {
    return token ? { Authorization: "Bearer " + token } : {};
  }

  /** The last paragraph of a question (the "Type yes, or: ..." instruction). */
  function instructionLine(question) {
    if (typeof question !== "string") return "";
    var parts = question.split(/\n\s*\n/).map(function (p) { return p.trim(); }).filter(Boolean);
    return parts.length ? parts[parts.length - 1] : "";
  }

  /** Removes the plain-text "Triage:" block from a review question (the web UI
   *  shows those items in their own panel) but keeps the final instruction. */
  function stripTriageText(question) {
    if (typeof question !== "string") return "";
    var idx = question.indexOf("\nTriage:");
    if (idx < 0) return question;
    return question.slice(0, idx).trim() + "\n\n" + instructionLine(question);
  }

  /** One-click replies for the confirmation and review steps. */
  function quickReplies(state) {
    if (!state) return [];
    if (state.summary) return ["yes"];
    if (typeof state.question === "string" && /Type approve/i.test(state.question)) return ["approve"];
    return [];
  }

  /** Splits a finished run's triage information for display. */
  function splitTriage(result) {
    result = result || {};
    var concerns = Array.isArray(result.canonical_concerns) ? result.canonical_concerns : [];
    var advisory = (Array.isArray(result.triage_findings) ? result.triage_findings : [])
      .filter(function (f) { return f.severity === "info"; });
    return {
      open: concerns.filter(function (c) { return !c.resolved; }),
      resolved: concerns.filter(function (c) { return c.resolved; }),
      advisory: advisory,
    };
  }

  function formatTimestamp(epochSeconds) {
    if (typeof epochSeconds !== "number") return "";
    return new Date(epochSeconds * 1000).toISOString().replace("T", " ").slice(0, 16) + " UTC";
  }

  function statusLabel(status) {
    if (status === "completed") return "Completed";
    if (status === "waiting_for_input") return "In progress";
    if (status === "error") return "Error";
    return String(status || "");
  }

  function apiBaseUrl() {
    if (typeof window !== "undefined") {
      var params = new URLSearchParams(window.location.search);
      var override = params.get("api");
      if (override) return override;
      if (window.BA_API_BASE) return window.BA_API_BASE;
    }
    return "http://localhost:8000";
  }

  return {
    formatValidationBadge: formatValidationBadge,
    classifyRequirementEvidence: classifyRequirementEvidence,
    isSessionActive: isSessionActive,
    isSessionComplete: isSessionComplete,
    summarizeArtifactCount: summarizeArtifactCount,
    formatBytes: formatBytes,
    apiBaseUrl: apiBaseUrl,
    buildTraceability: buildTraceability,
    svgToDataUri: svgToDataUri,
    authHeaders: authHeaders,
    instructionLine: instructionLine,
    stripTriageText: stripTriageText,
    quickReplies: quickReplies,
    splitTriage: splitTriage,
    formatTimestamp: formatTimestamp,
    statusLabel: statusLabel,
  };
});
